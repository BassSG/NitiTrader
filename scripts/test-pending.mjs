import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx={};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../backend/gas/Core.js',import.meta.url),'utf8'),ctx);
const t=1800000000000,step=300000;
const base={status:'PENDING',side:'BUY_LIMIT',entry:100,sl:95,tp:120,createdAt:t,expiresAt:t+12*step,pendingPolicy:{effectiveAt:t,maxDistance:10}};
const bar=(i,l,h,c)=>({t:t+i*step,o:c,l,h,c});
const run=(p,b)=>ctx.NitiCore.paper(p,b,step,t+20*step);
assert.equal(run(base,[bar(0,105,121,115)]).plan.status,'CANCELLED');
assert.equal(run({...base,side:'SELL_LIMIT',sl:105,tp:80},[bar(0,79,95,85)]).plan.status,'CANCELLED');
assert.equal(run(base,[bar(0,105,112,111)]).plan.status,'PENDING');
const first=run(base,[bar(0,105,112,111)]).plan;
assert.equal(run(first,[bar(0,105,112,111),bar(1,106,114,112)]).plan.status,'CANCELLED');
assert.equal(run(base,[bar(0,105,112,111),bar(1,105,109,108),bar(2,105,113,112)]).plan.status,'PENDING');
assert.equal(run(base,[bar(0,99,121,110)]).plan.status,'AMBIGUOUS');
assert.equal(run(base,[bar(0,99,113,112)]).plan.status,'FILLED');
assert.equal(run({...base,status:'FILLED',filledAt:t},[bar(0,105,121,115)]).plan.status,'TP');
assert.equal(run({...base,pendingPolicy:undefined},[bar(0,105,121,115)]).plan.status,'PENDING');
assert.equal(run({...base,expiresAt:t+step/2},[bar(0,105,111,110)]).plan.status,'EXPIRED');
assert.equal(run({...base,expiresAt:t+step/2},[bar(0,99,111,110)]).plan.status,'AMBIGUOUS');
assert.equal(run(base,[bar(2,105,121,115)]).plan.status,'AMBIGUOUS');
const cancelled=run(base,[bar(0,105,121,115)]);
assert.equal(cancelled.plan.closedAt,t+step);
assert.equal(cancelled.plan.resultR,undefined);
assert.equal(run(cancelled.plan,[bar(1,105,121,115)]).events.length,0);
assert.equal(base.status,'PENDING');
console.log('Pending policy: 16 assertions passed, including fill priority, gaps, expiry and idempotency');
